// Writes src/spawn/away-rates.ts, the shares and noise of M2.2c Ruling 8's summary month, fitted to a live town. It takes
// about 2.5 s: run it in any commit that changes CITY, CITY_RECORD or the economy day, and commit the result. --check
// compares instead, as test:headless does.
import { readFileSync, writeFileSync } from 'node:fs';
import { CITY } from '../src/economy/city.ts';
import { CITY_RECORD } from '../src/economy/city-record.ts';
import { economyDay } from '../src/economy/economy.ts';
import { PPM } from '../src/money/ppm.ts';
import { AWAY_FIELDS } from '../src/spawn/away.ts';
import { foldToLedger } from '../src/spawn/fold.ts';
import { createStandInTownHomes } from '../src/spawn/homes.ts';
import { LEDGER_FIELDS, scaleRecord } from '../src/spawn/record.ts';
import { spawnTown } from '../src/spawn/town.ts';
import { DAYS_PER_MONTH } from '../src/time/calendar.ts';
import { layoutWorld } from '../src/world/world.ts';

const FILE = new URL('../src/spawn/away-rates.ts', import.meta.url);
const NAME = 'packages/sim-core/src/spawn/away-rates.ts';
const HEADER = '// Generated by scripts/away-rates.ts. Do not edit.';

const PEOPLE = 1_000;
const SEEDS = [1, 2];
// The town needs its first two months to settle from the record onto its own cycle.
const FIRST_MONTH = 2;
const LAST_MONTH = 241;
// Ruling 8's floor on a share, so no field drifts without bound (unsourced estimate).
const MIN_SHARE = 0.01;
const LAYOUT_AGENTS = 1_024;
const LAYOUT_BYTES = 1 << 20;
const FIELD_NAMES = ['employed', 'price', 'wage'];

interface Fit {
  readonly record: number;
  readonly mean: number;
  readonly deviation: number;
  readonly lag1: number;
  readonly sharePpm: number;
  readonly noisePpm: number;
}

// A live town's AWAY_FIELDS at the start of months FIRST_MONTH to LAST_MONTH, one series each. A month's start is after
// the last day of the month before, the point at which CITY_RECORD was folded.
function monthStartLevels(seed: number): Float64Array[] {
  const world = layoutWorld(seed, 'phone', LAYOUT_AGENTS, LAYOUT_BYTES);
  spawnTown(world, createStandInTownHomes(world.ground, PEOPLE));
  const levels = FIELD_NAMES.map(() => new Float64Array(LAST_MONTH - FIRST_MONTH + 1));
  const row = new Float64Array(LEDGER_FIELDS);
  for (let month = 0; month <= LAST_MONTH; month++) {
    if (month >= FIRST_MONTH) {
      foldToLedger(world, row);
      for (let drift = 0; drift < AWAY_FIELDS.length; drift++) levels[drift][month - FIRST_MONTH] = row[AWAY_FIELDS[drift]];
    }
    if (month < LAST_MONTH) {
      for (let day = 0; day < DAYS_PER_MONTH; day++) economyDay(world, CITY, month * DAYS_PER_MONTH + day);
    }
  }
  return levels;
}

// An AR(1) about the runs' mean: the share is 1 - phi, phi being the lag-1 autocorrelation (pairs within a run), and the
// noise is s sqrt(1 - phi^2), s being the standard deviation. Ruling 8 says "about the record", but the record is one
// snapshot of seed 42, and at the first fit it sat 1 to 4 deviations off these runs' means, which put the price's and the
// wage's lag-1 about it above 1, where no share closes a gap.
function fitField(runs: readonly Float64Array[], record: number): Fit {
  let count = 0;
  let total = 0;
  for (const run of runs) {
    count += run.length;
    for (let t = 0; t < run.length; t++) total += run[t];
  }
  const mean = total / count;
  let variance = 0;
  let covariance = 0;
  for (const run of runs) {
    for (let t = 0; t < run.length; t++) {
      variance += (run[t] - mean) * (run[t] - mean);
      if (t + 1 < run.length) covariance += (run[t] - mean) * (run[t + 1] - mean);
    }
  }
  const lag1 = covariance / variance;
  const share = Math.min(1, Math.max(MIN_SHARE, 1 - lag1));
  const deviation = Math.sqrt(variance / count);
  // The noise follows the share the town will use, so a floored share still holds the town's own deviation.
  const noise = deviation * Math.sqrt(1 - (1 - share) * (1 - share));
  return {
    record,
    mean,
    deviation,
    lag1,
    sharePpm: Math.round(share * PPM),
    noisePpm: Math.round((noise / record) * PPM),
  };
}

function fitAll(): Fit[] {
  const runs = SEEDS.map(monthStartLevels);
  const first = new Float64Array(LEDGER_FIELDS);
  scaleRecord(CITY_RECORD, PEOPLE, first);
  const fits: Fit[] = [];
  for (let drift = 0; drift < AWAY_FIELDS.length; drift++) {
    fits.push(fitField(runs.map((run) => run[drift]), first[AWAY_FIELDS[drift]]));
  }
  return fits;
}

function moduleSource(fits: readonly Fit[]): string {
  const shares = fits.map((fit) => fit.sharePpm).join(', ');
  const noises = fits.map((fit) => fit.noisePpm).join(', ');
  return [
    HEADER,
    `// Fitted to a live CITY town of ${PEOPLE} people spawned from CITY_RECORD, at the starts of months ${FIRST_MONTH} to ${LAST_MONTH} on seeds ${SEEDS.join(' and ')}.`,
    `// One entry each for ${FIELD_NAMES.join(', ')}, in that order. A share is the part of its gap to the first record that a field`,
    "// closes in a month, and a noise the deviation of a month's step, as a share of the record's level at that size.",
    `export const AWAY_FIT_PEOPLE = ${PEOPLE};`,
    `export const AWAY_SHARE_PPM = /* @__PURE__ */ new Int32Array([${shares}]);`,
    `export const AWAY_NOISE_PPM = /* @__PURE__ */ new Int32Array([${noises}]);`,
    '',
  ].join('\n');
}

function report(fits: readonly Fit[]): void {
  fits.forEach((fit, drift) => {
    const offset = (fit.mean - fit.record) / fit.deviation;
    console.log(
      `${FIELD_NAMES[drift].padEnd(8)} record ${fit.record}, mean ${fit.mean.toFixed(1)} (${offset.toFixed(2)} sd from it), sd ${fit.deviation.toFixed(2)}, ` +
        `lag-1 ${fit.lag1.toFixed(4)}, share ${(fit.sharePpm / PPM).toFixed(4)}, noise ${(fit.noisePpm / PPM).toFixed(6)} of the record`,
    );
  });
}

const fits = fitAll();
report(fits);
const text = moduleSource(fits);
if (!process.argv.includes('--check')) {
  writeFileSync(FILE, text);
  console.log(`wrote ${NAME}`);
} else if (readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n') === text) {
  console.log(`${NAME} matches a fresh fit`);
} else {
  console.error(`${NAME} is out of date: run node packages/sim-core/scripts/away-rates.ts and commit the result`);
  process.exitCode = 1;
}
